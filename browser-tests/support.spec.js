const { test, expect } = require('@playwright/test');

test('archer management dialogs support keyboard cancellation and restore the initiating control', async ({page}) => {
  await page.goto('/#/archers');
  await page.getByRole('textbox', {name:'New archer name'}).fill('Riley Longbow');
  await page.getByRole('button', {name:'Add', exact:true}).click();
  await page.getByRole('button', {name:/Riley Longbow/}).click();
  await page.getByRole('button', {name:'Rename', exact:true}).click();
  const dialog = page.getByRole('dialog', {name:'Rename archer'});
  await expect(dialog).toBeVisible();
  await expect(dialog.getByRole('textbox', {name:'Rename archer'})).toBeFocused();
  await page.keyboard.press('Shift+Tab');
  await expect(dialog.getByRole('button', {name:'Save', exact:true})).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(dialog.getByRole('textbox', {name:'Rename archer'})).toBeFocused();
  await dialog.getByRole('textbox').fill('Unsaved name');
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('button', {name:'Rename', exact:true})).toBeFocused();
  await expect(page.getByRole('heading', {name:'Riley Longbow', exact:true})).toBeVisible();
  await page.getByRole('button', {name:'Rename', exact:true}).click();
  await page.getByRole('dialog').getByRole('textbox').fill('Riley Ridge');
  await page.getByRole('dialog').getByRole('button', {name:'Save', exact:true}).click();
  await expect(page.getByRole('heading', {name:'Riley Ridge', exact:true})).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', {name:'Riley Ridge', exact:true})).toBeVisible();
});

test('a saved backup restores real totals after overwrite confirmation and survives reload', async ({page}) => {
  const {readFile}=require('node:fs/promises');
  const db={archers:[{id:'a',name:'Riley Ridge',createdAt:1}],rounds:[{id:'past',type:'ibo',createdAt:1792972800000,finishedAt:1792976400000,status:'finished',targets:3,current:2,archerIds:['a'],scores:{a:[11,10,8]},note:'Sunday league'}]};
  await page.goto('/');
  await page.evaluate(db=>localStorage.setItem('ibo-scorer-v1',JSON.stringify(db)),db);
  await page.reload();
  await page.getByRole('button',{name:'Backup and export',exact:true}).first().click();
  const downloaded=page.waitForEvent('download');
  await page.getByRole('button',{name:'Save backup file',exact:true}).click();
  const backup=await readFile(await (await downloaded).path());
  await page.getByRole('navigation').getByRole('button',{name:'Archers',exact:true}).click();
  await page.getByRole('textbox',{name:'New archer name'}).fill('Temporary archer');
  await page.getByRole('button',{name:'Add',exact:true}).click();
  await page.getByRole('navigation').getByRole('button',{name:'Home',exact:true}).click();
  await page.getByRole('button',{name:'Backup and export',exact:true}).first().click();
  const upload=()=>page.getByLabel('Restore from backup file',{exact:true}).setInputFiles({name:'roundtrip.json',mimeType:'application/json',buffer:backup});
  await upload();
  const confirmation=page.getByRole('dialog',{name:'Restore this backup?'});
  await expect(confirmation).toContainText('Everything on this phone now (2 archers, 1 rounds) will be replaced');
  await confirmation.getByRole('button',{name:'Cancel',exact:true}).click();
  await expect(page.getByText(/2 archers,\s+1 round/).first()).toBeVisible();
  await upload();
  await page.getByRole('dialog',{name:'Restore this backup?'}).getByRole('button',{name:'Replace and restore',exact:true}).click();
  await page.getByRole('dialog',{name:'Backup restored'}).getByRole('button',{name:'OK',exact:true}).click();
  await page.reload();
  await page.getByRole('region',{name:'Recent rounds'}).getByRole('button',{name:/Riley Ridge, 29 points/}).click();
  await expect(page.getByRole('heading',{name:'Scorecard',exact:true})).toBeVisible();
  await expect(page.getByRole('table').first()).toContainText('29');
  await page.getByRole('navigation').getByRole('button',{name:'Archers',exact:true}).click();
  await expect(page.getByRole('button',{name:/Riley Ridge/})).toBeVisible();
  await expect(page.getByRole('button',{name:/Temporary archer/})).toHaveCount(0);
});

test('import preview preserves partial rounds, skips duplicates and makes parse errors recoverable', async ({page}) => {
  const path=require('node:path');
  await page.goto('/#/archers');
  await page.getByRole('textbox',{name:'New archer name'}).fill('Riley Ridge');
  await page.getByRole('button',{name:'Add',exact:true}).click();
  await page.getByRole('navigation').getByRole('button',{name:'Home',exact:true}).click();
  await page.getByRole('button',{name:'Backup and export',exact:true}).first().click();
  await page.getByLabel('Import scores from a file',{exact:true}).setInputFiles({name:'invalid.csv',mimeType:'text/csv',buffer:Buffer.from('Name,Score\nRiley,300')});
  await expect(page.getByRole('dialog',{name:'Could not read the file'})).toContainText('does not look like a score export');
  await page.getByRole('dialog').getByRole('button',{name:'OK',exact:true}).click();
  const fixture=path.join(__dirname,'../ibo-scorer/tests/fixtures/old-app-export.xlsx');
  await page.getByLabel('Import scores from a file',{exact:true}).setInputFiles(fixture);
  await expect(page.getByRole('heading',{name:'Import scores',exact:true})).toBeVisible();
  await expect(page.getByText('Saved unfinished',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Import 10 rounds for Riley Ridge',exact:true}).click();
  await page.getByRole('dialog',{name:'Scores imported'}).getByRole('button',{name:'OK',exact:true}).click();
  await expect(page.getByRole('heading',{name:'History',exact:true})).toBeVisible();
  await page.getByRole('navigation').getByRole('button',{name:'Home',exact:true}).click();
  await expect(page.getByRole('region',{name:'Unfinished rounds'}).getByRole('button',{name:/Resume Vegas 300/})).toContainText('144 points');
  await page.getByRole('button',{name:'Backup and export',exact:true}).first().click();
  await page.getByLabel('Import scores from a file',{exact:true}).setInputFiles(fixture);
  await expect(page.getByText('Already imported',{exact:true})).toHaveCount(10);
  await expect(page.getByRole('button',{name:'Nothing new to import',exact:true})).toBeDisabled();
});
